import { test, expect } from '@playwright/test'

const moduleFrame = 'iframe[data-acomet-module="media-keeper"]'
test('real Acomet sandbox, signed API, route state, themes and host-opened links',async({page},info)=>{
  const requests:{url:string;authorization?:string}[]=[]
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  page.on('request',request=>{if(request.url().startsWith('http://127.0.0.1:3002/api/media')&&request.method()==='GET')requests.push({url:request.url(),authorization:request.headers().authorization})})
  await page.goto('/m/media-keeper')
  const media=page.frameLocator(moduleFrame)
  await expect(media.getByRole('heading',{name:'理解 Acomet 的模块接入',exact:true})).toBeVisible()
  await expect(page.locator(moduleFrame)).toHaveAttribute('sandbox',/allow-scripts/)
  expect(requests.length).toBeGreaterThan(0)
  expect(requests.every(request=>request.authorization?.startsWith('Bearer '))).toBe(true)
  await media.getByRole('searchbox',{name:'标题关键词'}).fill('验收')
  await media.getByLabel('发布日期',{exact:true}).selectOption('week')
  await media.getByRole('button',{name:'查询',exact:true}).click()
  await expect(page).toHaveURL(/title=.*published=week/)
  await expect(media.getByRole('heading',{name:'验收资料 2',exact:true})).toBeVisible()
  await expect.poll(()=>new URL(requests.at(-1)!.url).searchParams.get('published')).toBe('week')
  await media.getByRole('navigation',{name:'资料类型'}).getByRole('link',{name:/^播客/}).click()
  await expect(page).toHaveURL(/source_type=podcast/)
  await expect(media.getByRole('heading',{name:'验收资料 3',exact:true})).toBeVisible()
  await media.getByRole('button',{name:'重置',exact:true}).click()
  await expect(media.getByRole('heading',{name:'理解 Acomet 的模块接入',exact:true})).toBeVisible()
  await media.getByRole('button',{name:'下一页',exact:true}).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(media.getByRole('heading',{name:'验收资料 24',exact:true})).toBeVisible()
  await media.getByRole('link',{name:'验收资料 24',exact:true}).click()
  await expect(page).toHaveURL(/media-keeper\/24\?page=2/)
  await expect(media.getByRole('heading',{name:'摘要',exact:true})).toBeVisible()
  await page.reload()
  await expect(media.getByRole('heading',{name:'摘要',exact:true})).toBeVisible()
  await media.getByRole('link',{name:'← 返回资料库'}).click()
  await expect(page).toHaveURL(/media-keeper\?page=2$/)
  await expect(media.getByRole('heading',{name:'验收资料 24',exact:true})).toBeVisible()
  await page.goBack()
  await expect(media.getByRole('heading',{name:'摘要',exact:true})).toBeVisible()
  const popup=page.waitForEvent('popup')
  await media.getByRole('link',{name:'阅读原文 ↗',exact:true}).click()
  const opened=await popup
  expect(opened.url()).toContain('example.org/reading/24')
  await opened.close()
  await page.getByRole('button',{name:'切换主题'}).click()
  await expect(media.locator('[data-media-theme]')).toHaveAttribute('data-media-theme','morning')
  expect(await media.locator('article').first().evaluate(element=>getComputedStyle(element).backgroundColor)).toBe('rgb(248, 245, 239)')
  expect(await media.locator('[data-media-theme]').evaluate(element=>getComputedStyle(element).fontFamily)).toContain('PingFang SC')
  await page.screenshot({path:info.outputPath('acomet-detail.png'),fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await media.getByRole('link',{name:'← 返回资料库'}).click()
  expect(await media.locator('body').evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:info.outputPath('acomet-mobile.png'),fullPage:true})
  expect(errors).toEqual([])
})

test('another simulated user is denied and can switch back to the owner',async({page})=>{
  await page.goto('/m/media-keeper')
  const media=page.frameLocator(moduleFrame)
  await expect(media.getByRole('heading',{name:'理解 Acomet 的模块接入',exact:true})).toBeVisible()
  await page.locator('#user').selectOption('bob')
  await expect(media.getByText('此账号没有访问该资料库的权限。',{exact:true})).toBeVisible()
  await expect(media.locator('article')).toHaveCount(0)
  await page.locator('#user').selectOption('alice')
  await expect(media.getByRole('heading',{name:'理解 Acomet 的模块接入',exact:true})).toBeVisible()
})

test('standalone entry explains how to open the module without requesting private data',async({page})=>{
  const calls:string[]=[]
  page.on('request',request=>{if(request.url().includes(':3002/api/'))calls.push(request.url())})
  await page.goto('http://localhost:5174')
  await expect(page.getByText('请从 Acomet 的 Media 工具页打开。',{exact:true})).toBeVisible()
  expect(calls).toEqual([])
})
